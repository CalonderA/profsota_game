const assert = require('node:assert/strict');
const Network = require('../specialties/ksk/network-model.js');
const n = new Network();
assert.equal(n.status().ok,false);
assert.equal(n.connect('router:wan','internet:net'),false);
assert.equal(n.place('router','rack'),false);
assert(n.place('router','hub2'));
assert.equal(n.place('switch','hub2'),false);
assert(n.place('switch','hub1'));
assert(n.place('server','rack'));
assert.equal(n.ports('switch').length,8);
assert.equal(n.connect('internet:net','router:lan'),false);
assert.equal(n.connect('router:wan','switch:1'),false);
assert.equal(n.links.length,0,'Rejected cables never occupy ports');
assert.equal(n.connect('internet:net','dev1:net'),false);
assert.equal(n.connect('switch:2','switch:3'),false);
assert.equal(n.connect('switch:9','dev1:net'),false);
for(const [i,d] of ['dev1','dev2','design1','design2','printer','server'].entries())assert(n.connect(d+':net','switch:'+(i+2)));
assert.equal(n.status().ok,false);
assert(n.connect('router:wan','internet:net'));
assert(n.connect('switch:1','router:lan'));
assert(n.status().ok);
n.remove(n.occupied('server:net').id);
assert.deepEqual(n.status().missing,['server']);
assert(!n.status().ok);
assert(n.connect('server:net','switch:8'));
assert(n.status().ok,'Any available switch port works');
assert.equal(n.place('server','rack'),false);
console.log('PASS: placement, occupied and invalid ports, wrong topology, disconnection and complete network.');
